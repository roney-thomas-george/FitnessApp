function fromCatalog(id: string, overrides?: Partial<ExerciseItem>): ExerciseItem {
  const c = EXERCISE_CATALOG.find((x) => x.id === id) || EXERCISE_CATALOG[0];
  return {
    id: `${id}-${Math.random().toString(36).slice(2, 6)}`,
    name: c.name,
    category: c.category,
    targetMuscle: c.targetMuscle,
    sets: c.sets,
    reps: c.reps,
    avatarType: 'letter',
    avatarLetter: c.avatarLetter,
    avatarBg: c.avatarBg,
    youtubeUrl: c.youtubeUrl,
    notes: c.notes,
    ...overrides,
  };
}

